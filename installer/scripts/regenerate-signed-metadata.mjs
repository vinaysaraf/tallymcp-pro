#!/usr/bin/env node
/**
 * Regenerate electron-updater metadata AFTER an external signer (SignPath)
 * re-signs the installer .exe.
 *
 * WHY: `pnpm package` runs electron-builder, which produces `latest.yml`
 * (+ `.blockmap`) and the `.exe.sha256` sidecar for the exe it just built.
 * If SignPath re-signs that exe as a SEPARATE post-build step, the exe bytes
 * change, so those files no longer describe it. electron-updater verifies the
 * download's SHA-512 against `latest.yml`, so a stale `latest.yml` makes EVERY
 * auto-update fail verification. This recomputes them against the SIGNED exe.
 *
 * DORMANT: only invoked by the release workflow's SignPath path, which runs
 * solely when the SIGNPATH_API_TOKEN secret is set. It never runs in today's
 * self-signed pipeline.
 *
 * ⚠️ UNTESTED against a real SignPath artifact — validate on a throwaway
 * pre-release tag before relying on it in production. See issue #17.
 *
 * Updates, in apps/configurator/dist-installer/:
 *   - <exe>.blockmap          (regenerated via app-builder, if resolvable)
 *   - latest.yml              (sha512 + size [+ blockMapSize] of the signed exe)
 *   - <exe>.sha256            (sidecar; also feeds generate-latest-json.mjs)
 * latest.json is regenerated by the workflow's existing generate-latest-json
 * step, which runs after this and reads the refreshed .sha256 sidecar.
 */

import { createHash } from "node:crypto";
import { readFile, writeFile, readdir, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, basename } from "node:path";
import { createRequire } from "node:module";
import { execFileSync } from "node:child_process";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..", "..");
const distDir = join(repoRoot, "apps", "configurator", "dist-installer");

/** base64 SHA-512 of a file — the exact form electron-updater stores/compares. */
async function sha512Base64(filePath) {
  return createHash("sha512")
    .update(await readFile(filePath))
    .digest("base64");
}

/** hex SHA-256 for the `.exe.sha256` sidecar (matches checksum.mjs / sha256sum). */
async function sha256Hex(filePath) {
  return createHash("sha256")
    .update(await readFile(filePath))
    .digest("hex");
}

/**
 * Regenerate the .blockmap and return the authoritative { sha512, blockMapSize }
 * exactly as electron-builder computes them, via the app-builder binary shipped
 * with electron-builder. Returns null if app-builder can't be resolved — the
 * caller then keeps the old blockmap; differential update simply falls back to a
 * full download (which is still SHA-512-verified against latest.yml).
 */
function regenerateBlockmap(exePath) {
  try {
    const require = createRequire(import.meta.url);
    const configuratorDir = join(repoRoot, "apps", "configurator");
    // app-builder-bin is a TRANSITIVE dep of electron-builder. Under pnpm's
    // strict node_modules it is not linked directly under the configurator, so
    // resolve it relative to electron-builder's own location as well.
    const paths = [configuratorDir];
    try {
      paths.push(dirname(require.resolve("electron-builder/package.json", { paths: [configuratorDir] })));
    } catch {
      /* electron-builder not resolvable here — fall through to fallback */
    }
    const pkgPath = require.resolve("app-builder-bin", { paths });
    const { appBuilderPath } = require(pkgPath);
    const stdout = execFileSync(
      appBuilderPath,
      ["blockmap", "--input", exePath, "--output", `${exePath}.blockmap`, "--compression", "gzip"],
      { encoding: "utf8" },
    );
    const parsed = JSON.parse(stdout);
    return { sha512: parsed.sha512, blockMapSize: parsed.blockMapSize };
  } catch (err) {
    console.warn(`[regen] app-builder blockmap unavailable (${err.message}); keeping old blockmap (updates fall back to full download).`);
    return null;
  }
}

/**
 * Rewrite latest.yml's file hash/size in place. electron-builder's format is
 * stable: `sha512` appears twice (the top-level entry at column 0 and the
 * files[] entry, both the whole-file hash), a single `size:` (the exe), and a
 * single `blockMapSize:`. Anchored, key-exact regexes avoid touching unrelated
 * keys (e.g. `size` never matches `blockMapSize`).
 */
function rewriteLatestYml(text, { sha512, size, blockMapSize }) {
  let out = text
    .replace(/^(sha512:).*$/m, `$1 ${sha512}`) // top-level
    .replace(/^(\s+sha512:).*$/m, `$1 ${sha512}`) // files[] entry
    .replace(/^(\s+size:)\s*\d+.*$/m, `$1 ${size}`);
  if (typeof blockMapSize === "number") {
    out = out.replace(/^(\s+blockMapSize:)\s*\d+.*$/m, `$1 ${blockMapSize}`);
  }
  return out;
}

async function main() {
  const entries = await readdir(distDir);
  const exeName = entries.find((n) => n.startsWith("TallyMCP-Setup-") && n.endsWith(".exe"));
  if (!exeName) {
    console.error(`[regen] no TallyMCP-Setup-*.exe in ${distDir}`);
    process.exit(1);
  }
  const exePath = join(distDir, exeName);
  const size = (await stat(exePath)).size;

  // Regenerate blockmap (authoritative sha512) if possible; else compute ourselves.
  const blockmap = regenerateBlockmap(exePath);
  const sha512 = blockmap?.sha512 ?? (await sha512Base64(exePath));
  const blockMapSize = blockmap?.blockMapSize;

  // latest.yml
  const ymlPath = join(distDir, "latest.yml");
  const yml = await readFile(ymlPath, "utf8");
  const newYml = rewriteLatestYml(yml, { sha512, size, blockMapSize });
  await writeFile(ymlPath, newYml, "utf8");

  // .exe.sha256 sidecar (also consumed by generate-latest-json.mjs)
  const sha256 = await sha256Hex(exePath);
  await writeFile(`${exePath}.sha256`, `${sha256}  ${basename(exePath)}\n`, "utf8");

  // Fail-closed self-check: the on-disk latest.yml must now match the signed exe.
  const verify = await sha512Base64(exePath);
  const written = await readFile(ymlPath, "utf8");
  const occurrences = (written.match(new RegExp(verify.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g")) || []).length;
  if (verify !== sha512 || occurrences < 2 || !written.includes(`size: ${size}`)) {
    console.error("[regen] self-check FAILED — latest.yml does not match the signed exe. Aborting so a broken update feed is never published.");
    process.exit(1);
  }

  console.log(`[regen] signed ${exeName}: size=${size}, sha512(base64)=${sha512.slice(0, 16)}…, sha256=${sha256.slice(0, 16)}…`);
  console.log(`[regen] latest.yml + .sha256${blockmap ? " + .blockmap" : ""} regenerated and self-verified.`);
}

main().catch((err) => {
  console.error("[regen] failure:", err);
  process.exit(1);
});
